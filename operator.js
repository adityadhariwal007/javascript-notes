// aritmatic operators
// + ------ Addition
// - ------ subtraction
// * ------ multiplication
// / ------ division
// % ------ modulus
// ** ------ power
let a = 10;
let b = 5;
console.log(a+b);

console.log(a-b);
console.log(a*b);
console.log(a/b);
console.log(a%b);
console.log(a**b);

// comparison operators
// == equals value
// != not equal
// >greater Than
// < smaller than
// >= greater than or equal
// <= less than or equal
console.log(10 > 5 );
console.log(10 == 5 );
console.log(10 < 5 );
console.log(10 != 5 );

// logical operators

